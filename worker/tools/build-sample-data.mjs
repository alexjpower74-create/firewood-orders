// Generates the Worker's SAMPLE data files. Run from worker/: `node tools/build-sample-data.mjs`.
//   ../data/sample-places.json → src/sample-places.js   (the Worker never reads outside worker/)
//   src/sample.js statements   → migrations/0002_sample.sql (the same statements POST /api/test/reset runs)
// `--check` writes nothing and exits 1 if either committed file differs from what would be generated.
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const WORKER = path.join(path.dirname(fileURLToPath(import.meta.url)), '..')
const check = process.argv.includes('--check')

export function renderPlaces(json) {
  const places = json.places.map((p) => ({ name: p.name, lat: p.lat, lng: p.lng, km_from_springdale: p.km_from_springdale }))
  return `// GENERATED by tools/build-sample-data.mjs from data/sample-places.json. Do not edit.\n` +
    `// ${json.source}. ${json.licence}.\n` +
    `// Real community points; the people and the dealer that use them are SAMPLE. No house numbers.\n` +
    `export const SAMPLE_PLACES = ${JSON.stringify(places, null, 2)}\n`
}

const literal = (v) => {
  if (v === null || v === undefined) return 'NULL'
  if (typeof v === 'number') return String(v)
  if (typeof v === 'boolean') return v ? '1' : '0'
  return `'${String(v).replace(/'/g, "''")}'`
}

export function renderSql(statements) {
  const lines = ['-- GENERATED by tools/build-sample-data.mjs from src/sample.js. Do not edit.',
    '-- The SAMPLE dealer settings, products and PINs (dealer 1357, driver 2580), as PBKDF2-SHA256 hash + salt.', '']
  for (const { sql, params } of statements) {
    let i = 0
    const out = sql.replace(/\?/g, () => literal(params[i++]))
    if (i !== params.length) throw new Error(`placeholder count mismatch in: ${sql}`)
    lines.push(`${out};`)
  }
  return lines.join('\n') + '\n'
}

async function main() {
  const placesFile = path.join(WORKER, 'src', 'sample-places.js')
  const sqlFile = path.join(WORKER, 'migrations', '0002_sample.sql')
  const placesText = renderPlaces(JSON.parse(readFileSync(path.join(WORKER, '..', 'data', 'sample-places.json'), 'utf8')))
  const current = (f) => { try { return readFileSync(f, 'utf8') } catch { return '' } }
  if (!check) writeFileSync(placesFile, placesText)
  // sample.js imports sample-places.js, so render the SQL after the places file exists.
  const { sampleStatements } = await import(path.join(WORKER, 'src', 'sample.js'))
  const sqlText = renderSql(sampleStatements())
  if (check) {
    const stale = [[placesFile, placesText], [sqlFile, sqlText]].filter(([f, t]) => current(f) !== t).map(([f]) => f)
    if (stale.length) {
      console.error(`stale generated files: ${stale.join(', ')}`)
      process.exit(1)
    }
    console.log('generated files up to date')
    return
  }
  writeFileSync(sqlFile, sqlText)
  console.log(`wrote ${path.relative(WORKER, placesFile)} and ${path.relative(WORKER, sqlFile)}`)
}

if (process.argv[1] === fileURLToPath(import.meta.url)) await main()
